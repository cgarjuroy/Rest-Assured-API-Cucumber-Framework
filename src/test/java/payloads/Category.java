package payloads;

public class Category {
	
	//properties
	private int id;
	private String name;
	
	//Constructors
	public Category() {
		super();
	}
	
	//Getter and Setter
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
}
